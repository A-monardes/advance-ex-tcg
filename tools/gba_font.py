def width(s: str, small: bool = False) -> int:
    table = SMALL if small else G
    w = 0
    for ch in s:
        g = table.get(ch, table.get("?", table.get(" ")))
        w += len(g[0]) + 1
    return max(0, w - 1)


def draw(img, x: int, y: int, s: str, color, shadow=None, small: bool = False):
    """Dibuja el texto con la esquina de arriba de la celda en (x, y).
    La sombra (estilo GBA) va a la derecha, abajo y en diagonal."""
    table = SMALL if small else G
    px = img.load()
    W, Hh = img.size
    cx = x
    for ch in s:
        g = table.get(ch, table.get("?", table.get(" ")))
        pts = [(cx + i, y + j) for j, row in enumerate(g) for i, c in enumerate(row) if c == "#"]
        if shadow is not None:
            for (a, b) in pts:
                for (da, db) in ((1, 0), (0, 1), (1, 1)):
                    if 0 <= a + da < W and 0 <= b + db < Hh and (a + da, b + db) not in pts:
                        px[a + da, b + db] = shadow
        for (a, b) in pts:
            if 0 <= a < W and 0 <= b < Hh:
                px[a, b] = color
        cx += len(g[0]) + 1
    return cx - x
