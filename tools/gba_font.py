H = 10


def _g(rows_from_1: str, row0: str = "", width: int = 0):
    """rows_from_1: filas 1..9 separadas por espacios ('-' = fila vacía)."""
    rows = rows_from_1.split()
    w = width or max(len(r) for r in rows if r != "-")
    out = [(row0 or "").ljust(w, ".")]
    for r in rows:
        out.append(("." * w) if r == "-" else r.ljust(w, "."))
    while len(out) < H:
        out.append("." * w)
    return out


